BEGIN TRAN

-- 1) codigo ARCA a los paises existentes (por nombre, o por nomlocal); ARGENTINA no se toca
UPDATE p SET p.codpais = x.codigo
FROM dbo.paises p
JOIN @arca x ON RTRIM(p.nombre) = RTRIM(ISNULL(x.nomlocal, x.nombre))
WHERE RTRIM(p.nombre) <> 'ARGENTINA' AND p.codpais <> x.codigo
PRINT 'paises actualizados: ' + CAST(@@ROWCOUNT AS varchar(10))

-- 2) los que faltan (ni por codigo ni por nombre); ARGENTINA (200) ya existe
INSERT INTO dbo.paises (nombre, codpais)
SELECT x.nombre, x.codigo FROM @arca x
WHERE x.codigo <> '200'
  AND NOT EXISTS (SELECT 1 FROM dbo.paises p WHERE RTRIM(p.codpais) = RTRIM(x.codigo))
  AND NOT EXISTS (SELECT 1 FROM dbo.paises p WHERE RTRIM(p.nombre) = RTRIM(ISNULL(x.nomlocal, x.nombre)))
  AND NOT EXISTS (SELECT 1 FROM dbo.paises p WHERE RTRIM(p.nombre) = RTRIM(x.nombre))
ORDER BY x.nombre
PRINT 'paises agregados: ' + CAST(@@ROWCOUNT AS varchar(10))

COMMIT TRAN

